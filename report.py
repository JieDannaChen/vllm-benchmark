#!/usr/bin/env python3
"""
Benchmark Report Generator
===========================
Generates a human-readable Markdown or HTML report from a benchmark
results JSON file. Use this to publish results in PRs, docs, or CI.

Usage:
    python report.py results/run_sequential_xxx.json --format markdown
    python report.py results/run_sequential_xxx.json --format html --output report.html
"""

import argparse
import json
import sys
from pathlib import Path
from datetime import datetime


def load_results(path: str) -> dict:
    with open(path) as f:
        return json.load(f)


def _fmt_ms(v) -> str:
    """Format a value in ms, or N/A if missing."""
    return f"{v:.2f}" if v is not None else "N/A"


def generate_markdown(result: dict) -> str:
    s = result["summary"]
    ts = result.get("timestamp", "unknown")

    lines = []
    lines.append("# Inference Performance Benchmark Report")
    lines.append("")
    lines.append(f"**Model:** {s['model']}  ")
    lines.append(f"**Mode:** {s['mode']}  ")
    lines.append(f"**Timestamp:** {ts}  ")
    lines.append(f"**Successful requests:** {s['successful_requests']} / {s['total_requests']}  ")
    lines.append(f"**Total tokens generated:** {s['total_tokens']:,}  ")
    lines.append(f"**Throughput:** {s['throughput_tok_s']} tokens / sec  ")
    if s["mode"] == "concurrent":
        lines.append(f"**Concurrent clients:** {s['concurrent_clients']}  ")
        lines.append(f"**Wall time:** {s['wall_time_s']}s  ")
    lines.append("")

    # Per-prompt table
    lines.append("## Per-Prompt Breakdown")
    lines.append("")
    lines.append("| Prompt | Name | Runs | TTFT (s) | TPOT (ms) | ITL (ms) | Avg Tokens |")
    lines.append("|--------|------|------|----------|-----------|----------|------------|")
    for pid, info in sorted(s["per_prompt"].items()):
        ttft = f"{info['avg_ttft_s']:.3f}" if info.get("avg_ttft_s") else "N/A"
        tpot = f"{info['avg_tpot_ms']:.2f}" if info.get("avg_tpot_ms") else "N/A"
        itl = f"{info['avg_itl_ms']:.2f}" if info.get("avg_itl_ms") else "N/A"
        lines.append(f"| {pid} | {info['name']} | {info['runs']} | {ttft} | {tpot} | {itl} | {info['avg_tokens']:.0f} |")
    lines.append("")

    # Percentile detail
    lines.append("## Latency Percentiles")
    lines.append("")
    lines.append("| Prompt | TTFT avg (ms) | TPOT p50 (ms) | TPOT p95 (ms) | ITL p50 (ms) | ITL p95 (ms) | ITL p99 (ms) |")
    lines.append("|--------|---------------|---------------|---------------|--------------|--------------|--------------|")
    for pid, info in sorted(s["per_prompt"].items()):
        ttft = f"{info['avg_ttft_s']*1000:.1f}" if info.get("avg_ttft_s") else "N/A"
        lines.append(
            f"| {pid} | {ttft} | {_fmt_ms(info.get('p50_tpot_ms'))} | "
            f"{_fmt_ms(info.get('p95_tpot_ms'))} | {_fmt_ms(info.get('itl_p50_ms'))} | "
            f"{_fmt_ms(info.get('p95_itl_ms'))} | {_fmt_ms(info.get('itl_p99_ms'))} |"
        )
    lines.append("")

    lines.append("## Environment")
    lines.append("")
    cfg = result.get("config", {})
    target = cfg.get("target", {})
    bench = cfg.get("benchmark", {})
    lines.append(f"- **Endpoint:** {target.get('base_url', 'N/A')}")
    lines.append(f"- **Model:** {target.get('model', 'N/A')}")
    lines.append(f"- **Mode:** {bench.get('mode', 'N/A')}")
    lines.append(f"- **Max tokens:** {bench.get('max_tokens', 'N/A')}")
    lines.append(f"- **Temperature:** {bench.get('temperature', 'N/A')}")
    lines.append(f"- **Repeats per prompt:** {bench.get('repeats_per_prompt', 'N/A')}")
    lines.append("")

    lines.append("---")
    lines.append(f"*Generated by vllm-benchmark at {ts}*")
    return "\n".join(lines)


def generate_html(result: dict) -> str:
    md = generate_markdown(result)
    # Very basic markdown → HTML conversion for standalone use.
    # We keep it dependency-free (no mistune needed).
    try:
        import markdown
        body = markdown.markdown(md, extensions=["tables"])
    except ImportError:
        # Fallback: wrap in pre
        body = f"<pre>{md}</pre>"

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>Inference Benchmark Report</title>
<style>
  body {{ font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
         max-width: 960px; margin: 2em auto; padding: 0 1em; line-height: 1.6; color: #24292f; }}
  h1 {{ border-bottom: 1px solid #eaecef; padding-bottom: .3em; }}
  h2 {{ margin-top: 1.5em; border-bottom: 1px solid #eaecef; padding-bottom: .2em; }}
  table {{ border-collapse: collapse; width: 100%; margin: 1em 0; }}
  th, td {{ border: 1px solid #d0d7de; padding: 6px 12px; text-align: left; }}
  th {{ background: #f6f8fa; font-weight: 600; }}
  tr:nth-child(even) {{ background: #f6f8fa; }}
  code {{ background: #f6f8fa; padding: .2em .4em; border-radius: 3px; font-size: 85%; }}
  pre {{ background: #f6f8fa; padding: 1em; border-radius: 6px; overflow-x: auto; }}
  hr {{ border: 0; border-top: 1px solid #eaecef; margin: 2em 0; }}
</style>
</head>
<body>
{body}
</body>
</html>"""


def main():
    parser = argparse.ArgumentParser(description="Generate benchmark report from results JSON")
    parser.add_argument("results", help="Path to benchmark results JSON")
    parser.add_argument("--format", choices=["markdown", "html"], default="markdown")
    parser.add_argument("--output", default=None, help="Output file path (default: stdout)")
    args = parser.parse_args()

    result = load_results(args.results)

    if args.format == "html":
        content = generate_html(result)
    else:
        content = generate_markdown(result)

    if args.output:
        Path(args.output).write_text(content)
        print(f"Report written to {args.output}")
    else:
        print(content)

    return 0


if __name__ == "__main__":
    sys.exit(main())
